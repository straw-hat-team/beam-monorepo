defmodule Trogon.Dispatcher.DispatchOptions do
  @moduledoc """
  Caller-supplied options for a dispatch.

  Everything a caller is allowed to seed the `Trogon.Dispatcher.Context` with lives here. `private` is deliberately
  absent: it is middleware scratch space, not caller input.

  `message_id` identifies the message being dispatched. `causation_id` names the `message_id` of whatever message
  caused it. Neither is generated by the library: a caller sets them, or leaves both `nil`.

  Build it with `new/1` or `new!/1`, which hold the invariants. Everything downstream trusts options it receives, so a
  struct literal that skips them is a bug at the call site.
  """

  alias Trogon.Dispatcher.InvalidDispatchOptionsError

  defstruct message_id: nil,
            correlation_id: nil,
            causation_id: nil,
            actor: nil,
            assigns: %{}

  @type t :: %__MODULE__{
          message_id: term() | nil,
          correlation_id: term() | nil,
          causation_id: term() | nil,
          actor: term() | nil,
          assigns: %{optional(atom()) => term()}
        }

  @type option ::
          {:message_id, term() | nil}
          | {:correlation_id, term() | nil}
          | {:causation_id, term() | nil}
          | {:actor, term() | nil}
          | {:assigns, %{optional(atom()) => term()}}

  @keys [:message_id, :correlation_id, :causation_id, :actor, :assigns]

  @doc """
  Builds options, returning an error when they break an invariant.

  ## Example

      {:ok, options} = DispatchOptions.new(actor: actor, assigns: %{request_id: "req-1"})
  """
  @spec new([option()]) :: {:ok, t()} | {:error, InvalidDispatchOptionsError.t()}
  def new(opts \\ []) do
    with :ok <- validate_keyword(opts),
         :ok <- validate_keys(opts),
         assigns = Keyword.get(opts, :assigns, %{}),
         :ok <- validate_assigns(assigns) do
      {:ok,
       %__MODULE__{
         message_id: Keyword.get(opts, :message_id),
         correlation_id: Keyword.get(opts, :correlation_id),
         causation_id: Keyword.get(opts, :causation_id),
         actor: Keyword.get(opts, :actor),
         assigns: assigns
       }}
    end
  end

  @doc """
  Builds options, raising `Trogon.Dispatcher.InvalidDispatchOptionsError` when they break an invariant.
  """
  @spec new!([option()]) :: t()
  def new!(opts \\ []) do
    case new(opts) do
      {:ok, options} -> options
      {:error, error} -> raise error
    end
  end

  defp validate_assigns(assigns) do
    cond do
      not is_map(assigns) ->
        {:error, InvalidDispatchOptionsError.exception(field: :assigns, value: assigns, reason: :not_a_map)}

      not Enum.all?(Map.keys(assigns), &is_atom/1) ->
        {:error, InvalidDispatchOptionsError.exception(field: :assigns, value: assigns, reason: :non_atom_key)}

      true ->
        :ok
    end
  end

  defp validate_keyword(opts) do
    if Keyword.keyword?(opts) do
      :ok
    else
      {:error, InvalidDispatchOptionsError.exception(field: nil, value: opts, reason: :not_a_keyword)}
    end
  end

  defp validate_keys(opts) do
    case Enum.reject(Keyword.keys(opts), &(&1 in @keys)) do
      [] ->
        :ok

      [key | _rest] ->
        {:error, InvalidDispatchOptionsError.exception(field: key, value: opts[key], reason: :unknown_key)}
    end
  end
end
